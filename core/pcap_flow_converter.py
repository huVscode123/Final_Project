# ============================================================
# core/pcap_flow_converter.py
# CICIDS2017 CSV 相容候選版（v4；先行對照驗證，不直接視為正式版）
#
# 目的：
#   讓 CICDDoS2019 / CICIDS2017 / Malware Traffic Analysis（MTA）等
#   「只有原始 PCAP、沒有現成 CSV」的測試資料，能被轉換成與既有
#   core/dataset_loader.py（CICIDSLoader / CICDDoS2019Loader）訓練時
#   所使用的 CICFlowMeter 統計特徵格式一致的 CSV 檔案，因此可以直接
#   餵給「維持原樣、以 CSV 特徵訓練」的既有模型做測試/推論。
#
#   本檔案不依賴、也不修改任何既有的訓練程式碼
#   （core/dataset_loader.py、run_training.py 等完全不變）。
#
# 與 core/packet_visualizer.py 的差異（重要）：
#   packet_visualizer.py 是把「封包原始位元組」轉成 32×32 影像，
#   對應的是另一套「封包位元組原生」模型（core/train_packet_native_vae.py
#   那條路線）。
#   本檔案做的是完全相反的事：把封包「還原成 CICFlowMeter 那種
#   逐 Flow 統計特徵」，對應的是「維持原樣、以 CSV 訓練」的既有
#   CICIDSLoader / CICDDoS2019Loader 那條路線。兩者不可混用，
#   詳見隨附的說明文件。
#
# 特徵定義：
#   修正項目：Payload Bytes、L4 Header Bytes、Active/Idle 5 秒門檻、
#   Subflow 1 秒計數、Flow timeout 年齡語意、timeout 後方向延續、FIN/RST。
#   Bulk 使用 CICFlowMeter 的狀態機近似實作；仍需與原版 CSV 抽樣比對，
#   不能只因名稱相同就宣稱與官方版本完全一致。
#
# v5 變更（CICIDS2017 legacy 相容模式）：
#   * 原版 FlowGenerator 對既有 Flow 的 FIN/RST 封包會先納入統計再關閉 Flow；
#     首包 FIN/RST 不會立刻關閉剛建立的 Flow。FIN 後的封包可能形成 appendix Flow。
#   * 新增 flag_mode=cicids2017_legacy_first_packet，重現已發布 CICIDS2017 CSV 的
#     TCP 旗標欄位只呈現 0/1 的 legacy 行為。通用逐包計數保留在 packet_count 模式。
#     舊 v4 實作的是 Engelen 修正版語意（雙向 FIN 或 RST 才結束），與訓練 CSV
#     的產生器不同，會造成 Flow 數量、FIN/RST/ACK 旗標與封包數分布差異。
#       "cicflowmeter_original"（預設）：第一個後續 FIN/RST 封包會結束既有 Flow。
#       "mutual_fin_rst"               ：舊 v4 行為（雙向 FIN 或 RST），保留供 A/B 對照。
#   * 新增 bulk_mode 參數。"cicids2017_zero"（預設）= 六個 Bulk 欄位輸出 0，僅符合
#     CICIDS2017 訓練 CSV 的觀察；"state_machine" = 使用 Bulk 狀態機近似計算，
#     供其他資料集使用。Bulk 零值不可視為跨資料集通用規則。
#   * 轉換結束時多印出：結束原因統計（FIN/RST/timeout/檔尾）與 Protocol 分布，
#     方便與訓練 CSV 的 Protocol 欄、Flow 數量對照。
